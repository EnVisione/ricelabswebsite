// Regenerates src/data/projects.js from the CurseForge Core API.
// Usage: npm run fetch-projects
//
// Reads CURSEFORGE_API_KEY from .env. Enumerates every project by both
// Nitro's and EnVy's authorId and writes the full registry.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')

function readEnv() {
  const path = resolve(ROOT, '.env')
  const text = readFileSync(path, 'utf8')
  const out = {}
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z_]+)\s*=\s*(.*)\s*$/)
    if (m) out[m[1]] = m[2]
  }
  return out
}

const env = readEnv()
const KEY = env.CURSEFORGE_API_KEY
if (!KEY) {
  console.error('Missing CURSEFORGE_API_KEY in .env')
  process.exit(1)
}

const AUTHORS = {
  nitro: 102638458,
  envy: 123828682,
  banane: 103863622,
}

// Editorial overrides that can't be inferred from CurseForge author tags alone.
// Any field here wins over whatever the API returns. Keyed by CF slug.
const OVERRIDES = {
  'server-essentials-forge': { name: 'Server Essentials Forge' }, // strip the "(LuckPerms)" suffix
  'emi-gamestages-integration': { builtFor: 'over-stars' },
  'integratedplaytime': { builtFor: 'over-stars' },
}

const CATEGORY_MAP = {
  modpacks: 'MODPACK',
  'mc-mods': 'MOD',
  'texture-packs': 'RESOURCE PACK',
}

async function fetchAuthor(authorId) {
  const all = []
  for (let index = 0; index < 500; index += 50) {
    const url = `https://api.curseforge.com/v1/mods/search?gameId=432&authorId=${authorId}&pageSize=50&index=${index}`
    const r = await fetch(url, { headers: { 'x-api-key': KEY, 'Accept': 'application/json' } })
    if (!r.ok) throw new Error(`CF ${r.status}: ${await r.text()}`)
    const json = await r.json()
    const data = json.data || []
    all.push(...data)
    if (data.length < 50) break
  }
  return all
}

function toEntry(m, owner) {
  const url = m.links?.websiteUrl || ''
  const parts = url.replace('https://www.curseforge.com/', '').split('/')
  const cat = parts[1] || ''
  const slug = parts[2] || m.slug
  return {
    slug,
    cf: `minecraft/${cat}/${slug}`,
    name: m.name,
    type: CATEGORY_MAP[cat] || cat.toUpperCase(),
    owner,
    downloads: m.downloadCount || 0,
  }
}

const nitroMods = await fetchAuthor(AUTHORS.nitro)
const envyMods = await fetchAuthor(AUTHORS.envy)
const bananeMods = await fetchAuthor(AUTHORS.banane)

// Deduplicate collabs by slug; nitro+envy collabs get owner 'both' (legacy).
// Banane is solo on his projects; any future overlap leaves the first-seen owner.
const combined = new Map()
for (const m of nitroMods) {
  const e = toEntry(m, 'nitro')
  combined.set(e.slug, e)
}
for (const m of envyMods) {
  const e = toEntry(m, 'envy')
  const existing = combined.get(e.slug)
  if (existing) combined.set(e.slug, { ...existing, owner: 'both' })
  else combined.set(e.slug, e)
}
for (const m of bananeMods) {
  const e = toEntry(m, 'banane')
  if (!combined.has(e.slug)) combined.set(e.slug, e)
}

// Apply editorial overrides before sorting.
for (const [slug, patch] of Object.entries(OVERRIDES)) {
  const entry = combined.get(slug)
  if (entry) combined.set(slug, { ...entry, ...patch })
}

const allSorted = [...combined.values()].sort((a, b) => b.downloads - a.downloads)
const mods = allSorted.filter((p) => p.type === 'MOD')
const modpacks = allSorted.filter((p) => p.type === 'MODPACK')
const rp = allSorted.filter((p) => p.type === 'RESOURCE PACK')

const totalDl = allSorted.reduce((s, p) => s + p.downloads, 0)

function stringify(p) {
  const { downloads, slug, cf, name, type, owner, ...rest } = p
  // Base fields first, then any editorial extras (builtFor, etc.) so overrides survive regeneration.
  const base = `slug: ${JSON.stringify(slug)}, cf: ${JSON.stringify(cf)}, name: ${JSON.stringify(name)}, type: ${JSON.stringify(type)}, owner: ${JSON.stringify(owner)}`
  const extras = Object.keys(rest).length
    ? ', ' + Object.entries(rest).map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join(', ')
    : ''
  return `  { ${base}${extras} },  // ${downloads.toLocaleString('en-US')}`
}

const out = `// Single source of truth for every RiceLabs project.
//
// Auto-generated by scripts/fetch-projects.mjs from the CurseForge Core API.
// Re-run \`npm run fetch-projects\` after publishing a new CurseForge project.
//
// Last synced: ${new Date().toISOString()}
// Total downloads at last sync: ${totalDl.toLocaleString('en-US')} across ${allSorted.length} projects

export const AUTHOR_IDS = {
  nitro: ${AUTHORS.nitro},
  envy: ${AUTHORS.envy},
  banane: ${AUTHORS.banane},
}

export const PROJECTS = [
  // In-development (no CF page)
  { slug: 'over-stars-the-one-ring', name: 'Over Stars: Origins of Indestructium', type: 'MODPACK', owner: 'both', inDev: true, internalLink: '/ool' },

  // Modpacks
${modpacks.map(stringify).join('\n')}

  // Mods
${mods.map(stringify).join('\n')}

  // Resource packs
${rp.map(stringify).join('\n')}
]

export const OWNER_LABEL = {
  envy: 'EnVy',
  nitro: 'Nitro',
  banane: 'Banane',
  both: 'EnVy + Nitro',
}
`

const targetPath = resolve(ROOT, 'src/data/projects.js')
writeFileSync(targetPath, out, 'utf8')
console.log(`✓ Wrote ${targetPath}`)
console.log(`  ${allSorted.length} projects · ${totalDl.toLocaleString('en-US')} downloads`)
